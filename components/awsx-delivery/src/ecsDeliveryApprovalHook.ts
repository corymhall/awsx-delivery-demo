import * as pulumi from '@pulumi/pulumi';
import { ApiHookAuthentication, PulumiApiHook } from './pulumiApiHook';
import { defaultEcsArrivalConditionName } from './ecsCheckpointDefaults';
import { parsePipelineStack } from './identifiers';

/**
 * Delivery stage and arrival condition targeted by the infrastructure hook.
 */
export enum EcsCheckpointCompletion {
  /**
   * Wait for the arrival and human approval gate.
   */
  APPROVAL = 'Approval',
  /**
   * Wait for the checkpoint stage's automated test Jobs.
   */
  AUTOMATED_TEST = 'AutomatedTest',
}

export interface EcsCheckpointSettings {
  /**
   * Delivery stage name. Use the pipeline checkpoint component's constructor name.
   */
  stageName: pulumi.Input<string>;
  /**
   * Named manual condition continued when ECS reaches test traffic. Default: ecs-arrival. Custom
   * names must match the pipeline checkpoint's conditionName.
   */
  conditionName?: pulumi.Input<string>;
  /**
   * Completion mode. Default: Approval. Must match the pipeline checkpoint.
   */
  completion?: pulumi.Input<EcsCheckpointCompletion>;
}

/**
 * Behavior when neither Delivery identity variable is present.
 */
export enum ManualUpdateBehavior {
  /**
   * Reject updates outside Delivery.
   */
  REJECT = 'Reject',
  /**
   * Allow ECS to proceed without Delivery approval.
   */
  BYPASS = 'Bypass',
}

/**
 * Inputs for the ECS approval integration.
 */
export interface EcsDeliveryApprovalHookArgs {
  /**
   * Fully qualified pipeline stack name, such as my-org/pipeline/dev. Validated against
   * DELIVERY_PIPELINE during Delivery runs. This is not a pipeline resource URN.
   */
  pipelineStack: pulumi.Input<string>;
  /**
   * Shared checkpoint stage and arrival condition.
   */
  checkpoint: EcsCheckpointSettings;
  /**
   * Existing authorized identity. Federation and Delivery grants remain external.
   */
  authentication: ApiHookAuthentication;
  /**
   * Existing execution role ARN. The caller manages trust; the component attaches its required
   * inline policy. Default: create a scoped execution role.
   */
  executionRoleArn?: pulumi.Input<string>;
  /**
   * Default: Reject. Bypass explicitly permits unapproved updates outside Delivery.
   */
  manualUpdates?: ManualUpdateBehavior;
  /**
   * Pulumi API endpoint. Default: https://api.pulumi.com.
   */
  apiUrl?: pulumi.Input<string>;
}

/**
 * ECS hook payload generated by this component.
 */
export interface EcsApprovalHookDetails {
  /**
   * Runtime mode, manual or delivery.
   */
  mode: string;
  /**
   * Delivery request. Absent for manual bypass.
   */
  call?: EcsApprovalHookCall;
}

/**
 * Request to continue the ECS arrival condition and wait for approval.
 */
export interface EcsApprovalHookCall {
  /**
   * Pulumi service name.
   */
  service: string;
  /**
   * API action.
   */
  action: string;
  /**
   * Wait for the human approval as well as the arrival condition.
   */
  waitForApproval: boolean;
  /**
   * Wait for the checkpoint stage to succeed after its gate passes.
   */
  waitForStage?: boolean;
  /**
   * Pipeline and stage coordinates.
   */
  parameters: EcsApprovalHookParameters;
  /**
   * Run-specific condition coordinates.
   */
  request: EcsApprovalHookRequest;
}

/**
 * Pipeline and stage coordinates.
 */
export interface EcsApprovalHookParameters {
  /**
   * Organization name.
   */
  organization: string;
  /**
   * Project name.
   */
  project: string;
  /**
   * Stack name.
   */
  stack: string;
  /**
   * Checkpoint stage name.
   */
  stage: string;
}

/**
 * Run-specific condition coordinates.
 */
export interface EcsApprovalHookRequest {
  /**
   * Positive integer run number encoded as a string.
   */
  runNumber: string;
  /**
   * Arrival condition name.
   */
  condition: string;
}

/**
 * Creates an authenticated approval Lambda and renders its ECS hook payload. Attach at
 * POST_TEST_TRAFFIC_SHIFT. Does not change an ECS service or manage invocation roles, teams,
 * grants, or issuer trust. Trust must exist before use.
 */
export class EcsDeliveryApprovalHook extends pulumi.ComponentResource {
  /**
   * Lambda ARN for the service's lifecycle hook.
   */
  public readonly functionArn: pulumi.Output<string>;
  /**
   * Execution identity for externally administered federation trust.
   */
  public readonly executionRoleArn: pulumi.Output<string>;
  /**
   * Payload for the service's lifecycle hook.
   */
  public readonly hookDetails: pulumi.Output<EcsApprovalHookDetails>;

  constructor(
    name: string,
    args: EcsDeliveryApprovalHookArgs,
    opts?: pulumi.ComponentResourceOptions,
  ) {
    super(
      'awsx-delivery:index:EcsDeliveryApprovalHook',
      name,
      {},
      pulumi.mergeOptions(opts, {
        aliases: [{ type: 'awsx-next-private:index:EcsDeliveryApprovalHook' }],
      }),
    );
    const pipeline = process.env.DELIVERY_PIPELINE;
    const run = process.env.DELIVERY_RUN;
    const isDelivery = pipeline !== undefined || run !== undefined;
    if (isDelivery && (!pipeline || !run || !/^[1-9][0-9]*$/.test(run))) {
      throw new Error('Delivery requires DELIVERY_PIPELINE and a positive integer DELIVERY_RUN');
    }
    const previewWithoutIdentity =
      !isDelivery &&
      args.manualUpdates !== ManualUpdateBehavior.BYPASS &&
      pulumi.runtime.isDryRun();
    if (
      !isDelivery &&
      args.manualUpdates !== ManualUpdateBehavior.BYPASS &&
      !previewWithoutIdentity
    ) {
      throw new pulumi.InputPropertyError({
        propertyPath: 'manualUpdates',
        reason: 'Run this update through Delivery, or explicitly select Bypass for manual updates.',
      });
    }
    const pipelineIdentity = pulumi.output(args.pipelineStack).apply(parsePipelineStack);
    const arrivalConditionName = pulumi
      .output(args.checkpoint.conditionName ?? defaultEcsArrivalConditionName)
      .apply((value) => {
        if (!value) {
          throw new pulumi.InputPropertyError({
            propertyPath: 'checkpoint.conditionName',
            reason: 'Provide a nonempty condition name matching the pipeline checkpoint.',
          });
        }
        return value;
      });
    const hook = new PulumiApiHook(
      name,
      {
        organization: pipelineIdentity.organization,
        authentication: args.authentication,
        executionRoleArn: args.executionRoleArn,
        apiUrl: args.apiUrl,
      },
      { parent: this },
    );
    this.functionArn = hook.functionArn;
    this.executionRoleArn = hook.executionRoleArn;
    // A local preview has no authorized run to encode. Leave the payload unknown,
    // rather than showing a manual bypass that a real update would reject.
    this.hookDetails = previewWithoutIdentity
      ? pulumi.output(pulumi.unknown).apply((): EcsApprovalHookDetails => ({ mode: 'delivery' }))
      : pulumi
          .output({
            identity: pipelineIdentity,
            checkpoint: args.checkpoint,
            conditionName: arrivalConditionName,
          })
          .apply(({ identity, checkpoint, conditionName }): EcsApprovalHookDetails => {
            if (!isDelivery) return { mode: 'manual' };
            if (pipeline !== `${identity.organization}/${identity.project}/${identity.stack}`) {
              throw new pulumi.InputPropertyError({
                propertyPath: 'pipelineStack',
                reason:
                  'DELIVERY_PIPELINE does not match pipelineStack. Configure the fully qualified stack that runs this pipeline.',
              });
            }
            if (
              checkpoint.completion !== undefined &&
              !Object.values(EcsCheckpointCompletion).includes(checkpoint.completion)
            ) {
              throw new Error('Invalid checkpoint completion mode');
            }
            return {
              mode: 'delivery',
              call: {
                service: 'Delivery',
                action: 'ContinueManualGate',
                waitForApproval: true,
                ...(checkpoint.completion === EcsCheckpointCompletion.AUTOMATED_TEST
                  ? { waitForStage: true }
                  : {}),
                parameters: { ...identity, stage: checkpoint.stageName },
                request: { runNumber: run!, condition: conditionName },
              },
            };
          });
    this.registerOutputs({
      functionArn: this.functionArn,
      executionRoleArn: this.executionRoleArn,
      hookDetails: this.hookDetails,
    });
  }
}
